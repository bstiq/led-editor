const FONTS: Record<FontSize, Record<string, number[]>> = {
  small: FONT_SMALL,
  medium: FONT_MEDIUM,
  large: FONT_LARGE,
}

export interface GlyphPixel {
  col: number
  row: number
}

function getGlyph(font: Record<string, number[]>, char: string): number[] {
  const key = char.toUpperCase()
  return font[key] ?? font[' ']
}

export function textPixels(text: string, fontSize: FontSize = 'medium'): GlyphPixel[] {
  const { width, height } = FONT_SIZES[fontSize]
  const font = FONTS[fontSize]
  const pixels: GlyphPixel[] = []
  let cursor = 0

  for (const char of text) {
    const glyph = getGlyph(font, char)
    for (let row = 0; row < height; row += 1) {
      const bits = glyph[row] ?? 0
      for (let col = 0; col < width; col += 1) {
        const mask = 1 << (width - 1 - col)
        if ((bits & mask) !== 0) {
          pixels.push({ col: cursor + col, row })
        }
      }
    }
    cursor += width + GLYPH_GAP
  }

  return pixels
}
