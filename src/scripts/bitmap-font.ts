export interface GlyphPixel {
  col: number
  row: number
}

function getGlyph(char: string): number[] {
  const key = char.toUpperCase()
  return FONT[key] ?? FONT[' ']
}

export function textPixels(text: string): GlyphPixel[] {
  const pixels: GlyphPixel[] = []
  let cursor = 0

  for (const char of text) {
    const glyph = getGlyph(char)
    for (let row = 0; row < GLYPH_HEIGHT; row += 1) {
      const bits = glyph[row] ?? 0
      for (let col = 0; col < GLYPH_WIDTH; col += 1) {
        const mask = 1 << (GLYPH_WIDTH - 1 - col)
        if ((bits & mask) !== 0) {
          pixels.push({ col: cursor + col, row })
        }
      }
    }
    cursor += GLYPH_WIDTH + GLYPH_GAP
  }

  return pixels
}
